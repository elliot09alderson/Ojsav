//Addition
let arr = [22, 33, 44, 55, 66, 77, 88, 99];
let sum = 0;
for (let i = 0; i < arr.length; i++) {
  sum = sum + arr[i];
}
console.log(sum);
//Multiplication
let abc = [23, 45, 67, 89];
let multiply = 1;
for (let a = 1; a < abc.length; a++) {
  multiply = multiply * abc[a];
}
console.log(multiply);
//Divition
let ans = [12, 23, 56, 67, 89, 90];
let div = 1;
for (let b = 1; b < ans.length; b++) {
  div = div / ans[b];
}
console.log(div);
//Subtraction
let asd = [11, 22, 33, 44, 55, 66, 77, 88, 99, 100];
let sub = 0;
for (let c = 0; c < asd.length; c++) {
  sub = sub - asd[c];
}
console.log(sub);
